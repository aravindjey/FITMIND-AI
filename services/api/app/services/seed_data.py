async def ensure_seed_data(session: AsyncSession) -> None:
    """Idempotently seeds exercises and validated food items if tables are empty."""
    ex_res = await session.execute(select(Exercise).limit(1))
    if not ex_res.scalars().first():
        for ex_data in DEFAULT_EXERCISES:
            session.add(Exercise(**ex_data))
        await session.commit()

    food_res = await session.execute(select(FoodItem).limit(1))
    if not food_res.scalars().first():
        for f_data in DEFAULT_FOOD_ITEMS:
            session.add(FoodItem(**f_data))
        await session.commit()
